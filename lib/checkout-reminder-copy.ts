import { createHmac, timingSafeEqual } from 'node:crypto';
import type { AdvisorLang } from './money.ts';

/** Un seul rappel, une heure après l’ouverture du paiement. */
export const CHECKOUT_REMINDER_DELAY_MS = 60 * 60 * 1000;

export function reminderAt(from: Date = new Date()): Date {
  return new Date(from.getTime() + CHECKOUT_REMINDER_DELAY_MS);
}

export function signOptOut(userId: string, secret: string): string {
  const body = userId.trim().toLowerCase();
  const sig = createHmac('sha256', secret).update(`checkout-opt-out:${body}`).digest('base64url');
  return `${body}.${sig}`;
}

export function readOptOut(token: string, secret: string): string | null {
  const split = token.split('.');
  if (split.length !== 2) return null;
  const [userId, sig] = split;
  if (!/^[0-9a-f-]{36}$/i.test(userId) || !sig) return null;
  const expected = signOptOut(userId, secret).split('.')[1];
  const left = Buffer.from(sig);
  const right = Buffer.from(expected);
  if (left.length !== right.length || !timingSafeEqual(left, right)) return null;
  return userId.toLowerCase();
}

export interface ReminderMail {
  subject: string;
  html: string;
}

export function checkoutReminderMail(input: {
  locale: AdvisorLang;
  name: string;
  offer: string;
  renewal: string;
  resumeUrl: string;
  unsubscribeUrl: string;
}): ReminderMail {
  const name = input.name.trim();
  const hello = input.locale === 'en'
    ? 'Hello'
    : input.locale === 'es'
      ? 'Hola'
      : input.locale === 'de'
        ? 'Guten Tag'
        : input.locale === 'it'
          ? 'Buongiorno'
          : 'Bonjour';
  const subject = subjectFor(input.locale);
  const lead = leadFor(input.locale);
  const cta = ctaFor(input.locale);
  const stop = stopFor(input.locale);
  const ai = aiFor(input.locale);
  const html = `<p>${hello}${name ? ` ${escapeHtml(name)}` : ''},</p>
<p>${escapeHtml(lead)}</p>
<p><strong>${escapeHtml(input.offer)}</strong></p>
<p>${escapeHtml(input.renewal)}</p>
<p><a href="${escapeHtml(input.resumeUrl)}">${escapeHtml(cta)}</a></p>
<p>${escapeHtml(ai)}</p>
<p><a href="${escapeHtml(input.unsubscribeUrl)}">${escapeHtml(stop)}</a></p>`;
  return { subject, html };
}

function subjectFor(locale: AdvisorLang): string {
  switch (locale) {
    case 'en':
      return 'Your Callastral payment is still open';
    case 'es':
      return 'Tu pago de Callastral sigue abierto';
    case 'de':
      return 'Ihre Callastral-Zahlung ist noch offen';
    case 'it':
      return 'Il tuo pagamento Callastral è ancora aperto';
    default:
      return 'Votre paiement Callastral est encore ouvert';
  }
}

function leadFor(locale: AdvisorLang): string {
  switch (locale) {
    case 'en':
      return 'You started a payment and did not finish it. The same price is still there.';
    case 'es':
      return 'Empezaste un pago y no lo terminaste. El mismo precio sigue disponible.';
    case 'de':
      return 'Sie haben eine Zahlung begonnen und nicht abgeschlossen. Derselbe Preis gilt noch.';
    case 'it':
      return 'Hai iniziato un pagamento e non l’hai concluso. Lo stesso prezzo è ancora lì.';
    default:
      return 'Vous avez commencé un paiement et ne l’avez pas terminé. Le même prix est toujours là.';
  }
}

function ctaFor(locale: AdvisorLang): string {
  switch (locale) {
    case 'en':
      return 'Return to payment';
    case 'es':
      return 'Volver al pago';
    case 'de':
      return 'Zurück zur Zahlung';
    case 'it':
      return 'Torna al pagamento';
    default:
      return 'Revenir au paiement';
  }
}

function stopFor(locale: AdvisorLang): string {
  switch (locale) {
    case 'en':
      return 'Unsubscribe from these reminders';
    case 'es':
      return 'Darse de baja de estos recordatorios';
    case 'de':
      return 'Diese Erinnerungen abbestellen';
    case 'it':
      return 'Disiscriviti da questi promemoria';
    default:
      return 'Se désinscrire de ces rappels';
  }
}

function aiFor(locale: AdvisorLang): string {
  switch (locale) {
    case 'en':
      return 'Callastral advisors are virtual. The voice is generated by AI.';
    case 'es':
      return 'Los consejeros Callastral son virtuales. La voz está generada por IA.';
    case 'de':
      return 'Callastral-Berater sind virtuell. Die Stimme wird von KI erzeugt.';
    case 'it':
      return 'I consulenti Callastral sono virtuali. La voce è generata dall’IA.';
    default:
      return 'Les conseillers Callastral sont virtuels. La voix est générée par IA.';
  }
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}
