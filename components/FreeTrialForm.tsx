export default function FreeTrialForm({ locale }: { locale: Locale }) {
  const copy = COPY[locale];
  const router = useRouter();
  const [firstName, setFirstName] = useState('');
  const [birthDate, setBirthDate] = useState('');
  const [birthTime, setBirthTime] = useState('');
  const [birthPlace, setBirthPlace] = useState('');
  const [heardFrom, setHeardFrom] = useState<HeardFromId | ''>('');
  const [consent, setConsent] = useState(false);
  const [hp, setHp] = useState('');
  const [error, setError] = useState('');
  const [pending, setPending] = useState(false);

  // Date saisie dans la mini-lecture de l’accueil : reprise ici pour ne pas la redemander.
  useEffect(() => {
    try {
      const saved = sessionStorage.getItem('cl_birth_date');
      if (saved && /^\d{4}-\d{2}-\d{2}$/.test(saved)) setBirthDate((current) => current || saved);
    } catch {
      /* stockage indisponible */
    }
  }, []);

  // Essai allégé : consentement IA puis appel tout de suite. L’e-mail (avec code) est demandé après l’appel.
  const start = async (event: FormEvent) => {
    event.preventDefault();
    setError('');
    setPending(true);
    postEvent('trial_start', { metadata: { source: 'essai', quick: 'true' } });
    const response = await fetch('/api/trial/quick', {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        firstName,
        locale,
        consent,
        heardFrom: heardFrom || null,
        [HONEYPOT_FIELD]: hp,
      }),
    });
    const payload = await response.json().catch(() => null);
    if (!response.ok || !payload?.trialId) {
      setPending(false);
      setError(payload?.error || 'Indisponible');
      return;
    }
    sessionStorage.setItem('trialId', payload.trialId);
    sessionStorage.setItem('trialQuick', '1');
    if (payload.advisorId) sessionStorage.setItem('astrologerId', payload.advisorId);
    sessionStorage.setItem('afterBirth', '/call');
    if (birthDate && birthPlace.trim()) {
      const saved = await fetch('/api/birth-data', {
        method: 'POST',
        headers: { 'Content-Type': 'application/json' },
        body: JSON.stringify({
          name: firstName.trim() || 'Vous',
          date: birthDate,
          time: birthTime,
          timeUnknown: !birthTime,
          place: birthPlace.trim(),
        }),
      }).catch(() => null);
      if (saved?.ok) {
        router.push('/call');
        return;
      }
    }
    router.push('/birth');
  };

  return (
    <div className="relative max-w-lg mx-auto px-4 py-10">
      <h1 className="font-[family-name:var(--font-cinzel)] text-3xl">{copy.title}</h1>
      <p className="mt-3 text-sm text-white/70">{copy.sub}</p>
      <form onSubmit={start} className="relative mt-6 space-y-3">
          <HoneypotField value={hp} onChange={setHp} />
          <details className="rounded-xl border border-white/10 px-3 py-2">
            <summary className="cursor-pointer text-sm text-white/70">{copy.more}</summary>
            <div className="mt-3 space-y-3">
          <label className="block text-sm">
            {copy.name}
            <input className="mt-1 w-full rounded-xl border border-white/20 bg-white/10 px-3 py-3" value={firstName} onChange={(event) => setFirstName(event.target.value)} autoComplete="given-name" />
          </label>
          <fieldset className="space-y-2">
            <legend className="text-sm text-white/70">{copy.birth}</legend>
            <label className="block text-sm">
              {copy.date}
              <input className="mt-1 w-full rounded-xl border border-white/20 bg-white/10 px-3 py-3" type="date" value={birthDate} onChange={(event) => setBirthDate(event.target.value)} />
            </label>
            <label className="block text-sm">
              {copy.time}
              <input className="mt-1 w-full rounded-xl border border-white/20 bg-white/10 px-3 py-3" type="time" value={birthTime} onChange={(event) => setBirthTime(event.target.value)} />
            </label>
            <label className="block text-sm">
              {copy.place}
              <input className="mt-1 w-full rounded-xl border border-white/20 bg-white/10 px-3 py-3" value={birthPlace} onChange={(event) => setBirthPlace(event.target.value)} autoComplete="address-level2" />
            </label>
          </fieldset>
          <HeardFromField locale={locale} value={heardFrom} onChange={setHeardFrom} />
            </div>
          </details>
          <label className="flex gap-2 text-sm text-white/80">
            <input type="checkbox" checked={consent} onChange={(event) => setConsent(event.target.checked)} required />
            <span>{copy.consent}</span>
          </label>
          <button type="submit" className="btn-primary w-full" disabled={pending || !consent}>{copy.confirm}</button>
          <p className="text-xs text-white/55">{copy.once}</p>
        </form>
      {error && <p className="mt-3 text-sm text-red-200" role="alert">{error}</p>}
    </div>
  );
}
